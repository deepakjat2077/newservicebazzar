<?php

namespace App\Services;

use App\Models\Subcategory;

/**
 * Writes seo_title / seo_keywords / seo_description for a subcategory.
 *
 * Shared by the listing form's quick-add and the backfill command, so both
 * produce identical output — the house rule being that seo_title is the
 * subcategory name exactly as typed, and only the keywords and description
 * come from the AI.
 */
class SubcategorySeoWriter
{
    protected AiContentGenerator $ai;

    public function __construct(AiContentGenerator $ai)
    {
        $this->ai = $ai;
    }

    public function isConfigured(): bool
    {
        return $this->ai->isConfigured();
    }

    /**
     * The whole set for one subcategory.
     *
     * @return array{seo_title: string, seo_keywords: string, seo_description: string, generated: bool, message: string}
     */
    public function generate(string $name, ?string $categoryName): array
    {
        $fallback = $this->fallback($name, $categoryName);

        if (!$this->ai->isConfigured()) {
            return $fallback + ['generated' => false, 'message' => 'AI key not configured; used default SEO.'];
        }

        $result = $this->ai->json($this->prompt($name, $categoryName));

        if (!$result['status']) {
            return $fallback + ['generated' => false, 'message' => $result['message']];
        }

        return $this->parse($result['data'], $name, $categoryName);
    }

    /**
     * The prompt. Public so the backfill command can run many of these
     * through one concurrent HTTP pool instead of one at a time.
     */
    public function prompt(string $name, ?string $categoryName): string
    {
        $context = $categoryName
            ? "The subcategory is \"{$name}\", which sits under the category \"{$categoryName}\"."
            : "The subcategory is \"{$name}\".";

        $examples = $this->styleExamples();

        return <<<PROMPT
You write SEO metadata for an Indian local business directory.

{$context}

"{$name}" is the name of a type of service or business — it is NOT a city,
area or place name. Never write it as a location (never "in {$name}").

Here are existing entries, for tone only:

{$examples}

The page title is already fixed as exactly "{$name}". Do not write a title.
You only write the keywords and the description.

Return JSON with exactly these keys:
{
  "seo_keywords": "...",
  "seo_description": "..."
}

Rules for seo_keywords:
- 6 to 10 comma-separated keywords, all lowercase
- the first keyword must be "{$name}" in lowercase
- no hashtags, no quotes

Rules for seo_description:
- 120-160 characters, one plain sentence or two
- must contain "{$name}"
- describes the service and its benefit, no fake claims

General: English, no links, no phone numbers, no emojis, no adult or illegal
content.
PROMPT;
    }

    /**
     * Turn a model answer into columns, falling back whenever it is unusable.
     *
     * @return array{seo_title: string, seo_keywords: string, seo_description: string, generated: bool, message: string}
     */
    public function parse(array $data, string $name, ?string $categoryName): array
    {
        $fallback = $this->fallback($name, $categoryName);

        $clean = function ($value, $limit) {
            $value = trim(preg_replace('/\s+/', ' ', strip_tags((string) $value)));

            return mb_substr($value, 0, $limit);
        };

        $keywords = $clean($data['seo_keywords'] ?? '', 500);
        $description = $clean($data['seo_description'] ?? '', 500);

        if ($keywords === '' || $description === '') {
            return $fallback + ['generated' => false, 'message' => 'AI answer was incomplete; used default SEO.'];
        }

        return [
            // Never from the AI: the name is the search term itself, so the
            // title always starts from fallback()'s deterministic version
            // (the bare name, or the bare name padded to fit Google's
            // ~30-char floor when the name alone is too short) rather than
            // whatever the model made up.
            'seo_title'       => $fallback['seo_title'],
            'seo_keywords'    => $keywords,
            'seo_description' => $description,
            'generated'       => true,
            'message'         => 'SEO generated by AI.',
        ];
    }

    /**
     * Deterministic version, used whenever the AI cannot be reached.
     *
     * @return array{seo_title: string, seo_keywords: string, seo_description: string}
     */
    public function fallback(string $name, ?string $categoryName): array
    {
        // Only used to build keyword variations, never the title.
        $subject = preg_match('/\bservices?\b/i', $name) ? $name : $name . ' Services';

        $keywords = collect([
            $name,
            $name . ' near me',
            'best ' . $name,
            $subject,
            $categoryName,
            $categoryName ? $categoryName . ' near me' : null,
        ])->filter()->map(function ($word) {
            return strtolower(trim($word));
        })->unique()->implode(', ');

        // The name alone is the right title when it's already long enough —
        // but most subcategory names are well under Google's ~30-char floor
        // ("Hotels", "Spa", "GST"), and shipping those as-is is exactly what
        // filled the SEO audit's "Title short" bucket with thousands of rows.
        // Pad only when needed, never touch a name that's already long enough.
        $title = mb_strlen($name) >= 30 ? $name : "Best {$subject} | ServiceBazzar";
        if (mb_strlen($title) > 60) {
            $title = mb_strlen($subject) >= 30 && mb_strlen($subject) <= 60 ? $subject : $name;
        }

        return [
            'seo_title' => mb_substr($title, 0, 255),
            'seo_keywords' => mb_substr($keywords, 0, 500),
            'seo_description' => mb_substr(
                'Get professional ' . $subject . ' from verified providers. Compare options, check contact details and choose the right one near you.',
                0,
                500
            ),
        ];
    }

    /**
     * Real rows used as few-shot examples, so generated SEO follows whatever
     * house style is already in the table rather than one invented here.
     *
     * Resolved once per process: the backfill command calls this thousands of
     * times and the answer does not change mid-run.
     */
    protected static ?string $examples = null;

    public function styleExamples(int $limit = 4): string
    {
        if (static::$examples !== null) {
            return static::$examples;
        }

        $rows = Subcategory::whereNotNull('seo_keywords')
            ->where('seo_keywords', '<>', '')
            ->whereNotNull('seo_description')
            ->where('seo_description', '<>', '')
            ->inRandomOrder()
            ->limit($limit)
            ->get(['name', 'seo_keywords', 'seo_description']);

        if ($rows->isEmpty()) {
            return static::$examples = <<<SAMPLE
Name: Web Development
seo_keywords: web development, website design, web developer, ecommerce website
seo_description: Get professional web development services including website design, eCommerce, and custom builds.
SAMPLE;
        }

        return static::$examples = $rows->map(function ($row) {
            return "Name: {$row->name}\n"
                . "seo_keywords: {$row->seo_keywords}\n"
                . "seo_description: {$row->seo_description}";
        })->implode("\n\n");
    }
}
